// Token Radar, model radar-2: a fresh entry for the token-radar-01 bounty.
//
// The program reads the sealed DefiLlama snapshot (input/snapshot.json), scores every
// pre-token protocol with the model below, writes the ranked board to board.json, writes
// the dashboard's data beside the page as data.js, copies dashboard/ and screenshots/ to
// the output directory, and writes dossier.json with the vendored make.fun library.
//
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input <snapshot.json>
//
// The model is one function of the snapshot's own figures, and no protocol name is ever
// special-cased:
//
//   base         = tvl_usd x 0.20
//   growth       = clamp(change_7d, -50, 100) per cent (unreported growth counts as 0)
//   growthMult   = 1 + (growth / 100) x 0.75
//   maturity     = 0.55 + min(age_days, 900) / 900 x 0.45   (age unknown: 270 days)
//   breadth      = 1 + 0.02 x min(max(chains - 1, 0), 4)    (multi-chain reach)
//   implied      = max(1, round(base x growthMult x maturity x breadth))
//
// TVL says how much value the protocol already holds. Seven-day growth says whether that
// value is still arriving. Age with no token says how long the protocol has run without
// issuing one, which is the closest thing the snapshot has to launch pressure. Breadth says
// how many chains the protocol already serves, because a launch lands harder where users
// already are. The board ranks the watchlist (the floor) first in coverage and adds the
// strongest pre-token protocols below the floor by TVL, so the early radar is the point.

